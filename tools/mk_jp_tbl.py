"""Generate tbl/jp.tbl: the Japanese font order (LZ77 font at 0x160698, 248 glyphs) plus the FF script commands.

Glyph readings verified against the decoded font sheet (tools/fontsheet.py) and known on-screen lines; see docs/re/text.md.
    python -X utf8 tools/mk_jp_tbl.py      # rewrites tbl/jp.tbl
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

LOW = ("　０１２３４５６７８９、。平．・"            # 00-0F
       "雪回？！＿ー／～向（）押動方石泉"            # 10-1F
       "一小村強力魔気見悪会中世界手助先"            # 20-2F
       "行森礼作出氷地下牢目家広草原人知"            # 30-3F
       "今火山道大樹海本体勝話考元全以上"            # 40-4F
       "水辺来♥")                                   # 50-53
# hiragana from 0x54; the small ぃぅぇぉ slots hold the GBA button letters A B L R; no ゐ ゑ
HIRA = ("ぁあＡいＢうＬえＲおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷ"
        "へべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわをん")
# 0xF2 is 口 (出口), not ヮ: the font has no ヮ
KATA = ("ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプ"
        "ヘベペホボポマミムメモャヤュユョヨラリルレロ口ワヲンヴ穴")

# FF xx commands: name and argument byte count (from the interpreter at 0801B338; docs/re/text.md)
CMDS = {0x00: ("end", 0), 0x01: ("n", 0), 0x02: ("c02", 1), 0x03: ("wait", 1), 0x04: ("clr", 0),
        0x05: ("c05", 0), 0x06: ("c06", 0), 0x07: ("c07", 0), 0x08: ("c08", 0), 0x09: ("face", 2),
        0x0A: ("c0A", 1), 0x0B: ("c0B", 1), 0x0C: ("c0C", 3), 0x0D: ("c0D", 3), 0x0E: ("c0E", 2),
        0x0F: ("c0F", 1), 0x10: ("c10", 1), 0x11: ("c11", 1), 0x12: ("c12", 1), 0x13: ("c13", 1),
        0x14: ("c14", 0), 0x15: ("c15", 2), 0x16: ("c16", 1), 0x17: ("c17", 1), 0x18: ("c18", 1),
        0x19: ("box", 1), 0x1A: ("c1A", 2), 0x1B: ("c1B", 1), 0x1C: ("c1C", 2), 0x1D: ("c1D", 0)}


def chars():
    s = LOW + HIRA + KATA
    assert len(s) == 248, len(s)
    return s


# Message strings (rescue / boss / system / menus / client): FF end, FE newline, FC page (wait for button),
# FD xx colour, F9 = the rescued demon's name (no argument: printing resumes at the next byte; 080062C0).
# docs/re/text.md "Other text".
MSG = {"FF": "{end}", "FE": "{n}", "FC": "{page}", "FD": "{col:1}", "F9": "{name}"}
# あそびかた tutorial (tools/tutorial.py): F8 xx demo action (arg bytes per F8ARGS), FA xx pause, rest as MSG
TUT_F8 = {0x00: 1, 0x01: 1, 0x02: 2, 0x03: 0, 0x04: 0, 0x05: 2, 0x06: 0, 0x07: 0, 0x08: 0, 0x09: 0, 0x0B: 1, 0x0C: 0}


def header(name):
    return ["# Puzzle de Call! %s table (generated by tools/mk_jp_tbl.py; do not edit by hand)" % name]


def glyphs():
    return ["%02X=%s" % (code, ch) for code, ch in enumerate(chars())]


def lines():
    out = header("Japanese") + glyphs()  # story scripts
    out.append("FF09FF={noface}")  # FF 09 FF: one argument byte only (the FF)
    for code, (name, argc) in CMDS.items():
        out.append("FF%02X={%s%s}" % (code, name, ":%d" % argc if argc else ""))
    return out


def msg_lines():
    return header("message-string") + glyphs() + ["%s=%s" % kv for kv in MSG.items()]


def tutorial_lines():
    out = header("tutorial-script") + glyphs() + ["%s=%s" % kv for kv in MSG.items() if kv[0] != "F9"]
    out.append("FA={pause:1}")
    out += ["F8%02X={demo%02X%s}" % (sub, sub, ":%d" % n if n else "") for sub, n in TUT_F8.items()]
    return out


TABLES = {"jp.tbl": lines, "msg.tbl": msg_lines, "tutorial.tbl": tutorial_lines}

if __name__ == "__main__":
    (ROOT / "tbl").mkdir(exist_ok=True)
    for name, fn in TABLES.items():
        (ROOT / "tbl" / name).write_text("\n".join(fn()) + "\n", encoding="utf-8", newline="\n")
        print("tbl/%s: %d lines" % (name, len(fn())))
