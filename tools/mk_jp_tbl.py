"""Generate tbl/jp.tbl: the Japanese font order (LZ77 font at 0x160698, 248 glyphs) plus the FF script commands.

Glyph readings verified against the decoded font sheet (tools/fontsheet.py) and known on-screen lines; see docs/re/text.md.
    python -X utf8 tools/mk_jp_tbl.py      # rewrites tbl/jp.tbl
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

LOW = ("　０１２３４５６７８９、。平．・"            # 00-0F
       "雪回？！＿ー／～向（）押動方右泉"            # 10-1F
       "一小村強力魔気見悪会中世界手助先"            # 20-2F
       "行森礼作出氷地下牢目家広草原人知"            # 30-3F
       "今火山道大樹海本体勝話考元全以上"            # 40-4F
       "水辺来♥")                                   # 50-53
# hiragana from 0x54; the small ぃぅぇぉ slots hold the GBA button letters A B L R; no ゐ ゑ
HIRA = ("ぁあＡいＢうＬえＲおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷ"
        "へべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわをん")
KATA = ("ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプ"
        "ヘベペホボポマミムメモャヤュユョヨラリルレロヮワヲンヴ穴")

# FF xx commands: name and argument byte count (from the interpreter at 0801B338; docs/re/text.md)
CMDS = {0x00: ("end", 0), 0x01: ("n", 0), 0x02: ("c02", 1), 0x03: ("wait", 1), 0x04: ("clr", 0),
        0x05: ("c05", 0), 0x06: ("c06", 0), 0x07: ("c07", 0), 0x08: ("c08", 0), 0x09: ("face", 2),
        0x0A: ("c0A", 1), 0x0B: ("c0B", 1), 0x0C: ("c0C", 3), 0x0D: ("c0D", 3), 0x0E: ("c0E", 2),
        0x0F: ("c0F", 1), 0x10: ("c10", 1), 0x11: ("c11", 1), 0x12: ("c12", 1), 0x13: ("c13", 1),
        0x14: ("c14", 0), 0x15: ("c15", 2), 0x16: ("c16", 1), 0x17: ("c17", 1), 0x18: ("c18", 1),
        0x19: ("box", 1), 0x1A: ("c1A", 2), 0x1B: ("c1B", 1), 0x1C: ("c1C", 2), 0x1D: ("c1D", 0)}


def chars():
    s = LOW + HIRA + KATA
    assert len(s) == 248, len(s)
    return s


def lines():
    out = ["# Puzzle de Call! Japanese table (generated by tools/mk_jp_tbl.py; do not edit by hand)"]
    for code, ch in enumerate(chars()):
        out.append("%02X=%s" % (code, ch))
    out.append("FF09FF={noface}")  # FF 09 FF: one argument byte only (the FF)
    for code, (name, argc) in CMDS.items():
        out.append("FF%02X={%s%s}" % (code, name, ":%d" % argc if argc else ""))
    return out


if __name__ == "__main__":
    (ROOT / "tbl").mkdir(exist_ok=True)
    (ROOT / "tbl" / "jp.tbl").write_text("\n".join(lines()) + "\n", encoding="utf-8", newline="\n")
    print("tbl/jp.tbl:", len(chars()), "glyphs,", len(CMDS) + 1, "commands")
